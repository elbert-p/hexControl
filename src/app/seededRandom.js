// src/app/seededRandom.js
// Small deterministic PRNG helpers so every player can generate identical puzzles
// from the same seed string (used by the daily Hexle).

/** Hash an arbitrary string into a 32-bit unsigned integer (xmur3-style). */
export function hashString(str) {
  let h = 1779033703 ^ str.length;
  for (let i = 0; i < str.length; i++) {
    h = Math.imul(h ^ str.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  h = Math.imul(h ^ (h >>> 16), 2246822507);
  h = Math.imul(h ^ (h >>> 13), 3266489909);
  return (h ^= h >>> 16) >>> 0;
}

/** mulberry32: returns a function producing floats in [0, 1), like Math.random. */
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Build a Math.random-compatible generator from a seed string. */
export function makeRng(seedString) {
  return mulberry32(hashString(String(seedString)));
}
